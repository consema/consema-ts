/** The two canonical materialization styles (materialization.rs:157-166). */
type Style = 'Xml' | 'Binary';

/** One validated `plist.value-tree@1` record. */
interface Record {
  readonly root: ValueNode;
  readonly policy: boolean;
}

/** One validated value record with its input path. */
interface ValueNode {
  readonly path: ValuePath;
  readonly kind: ValueKind;
}

/** One validated dictionary association. */
interface DictEntry {
  readonly key: string;
  readonly keyPath: ValuePath;
  readonly value: ValueNode;
}

/** Closed validated value kinds (materialization.rs:333-362). */
type ValueKind =
  | { readonly kind: 'Dict'; readonly entries: readonly DictEntry[] }
  | { readonly kind: 'Array'; readonly elements: readonly ValueNode[] }
  | { readonly kind: 'String'; readonly text: string }
  | { readonly kind: 'Integer'; readonly value: bigint }
  | { readonly kind: 'Real'; readonly real: PlistReal }
  | { readonly kind: 'Boolean'; readonly value: boolean }
  | { readonly kind: 'Date'; seconds: number }
  | { readonly kind: 'Data'; readonly bytes: Uint8Array }
  | { readonly kind: 'Uid'; readonly value: number };

/** One input value location paired with its exact target ordinal. */
interface InputItem {
  readonly path: ValuePath;
  readonly target: number;
}

