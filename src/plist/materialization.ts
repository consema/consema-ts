// -- XML ---------------------------------------------------------------------

function serializeXml(record: Record, limits: MaterializationLimits): { readonly bytes: Uint8Array; readonly items: InputItem[] } {
  const out = { text: '<?xml version="1.0" encoding="UTF-8"?>\n' };
  out.text += '<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">\n';
  out.text += '<plist version="1.0">\n';
  const items: InputItem[] = [];
  const rank = { value: 0 };
  emitValue(out, record.root, 1, items, rank, limits);
  out.text += '</plist>\n';
  return { bytes: new TextEncoder().encode(out.text), items };
}

/** Emits one value element at the given depth (materialization.rs:1123-1209). */
function emitValue(
  out: { text: string },
  node: ValueNode,
  depth: number,
  items: InputItem[],
  rank: { value: number },
  limits: MaterializationLimits,
): void {
  switch (node.kind.kind) {
    case 'Dict': {
      out.text += writeIndent(depth);
      if (node.kind.entries.length === 0) {
        out.text += '<dict></dict>\n';
      } else {
        out.text += '<dict>\n';
        for (const entry of node.kind.entries) {
          out.text += writeIndent(depth + 1);
          out.text += '<key>';
          out.text += escapeXmlText(entry.key);
          out.text += '</key>\n';
          emitValue(out, entry.value, depth + 1, items, rank, limits);
        }
        out.text += writeIndent(depth);
        out.text += '</dict>\n';
      }
      break;
    }
    case 'Array': {
      out.text += writeIndent(depth);
      if (node.kind.elements.length === 0) {
        out.text += '<array></array>\n';
      } else {
        out.text += '<array>\n';
        for (const element of node.kind.elements) {
          emitValue(out, element, depth + 1, items, rank, limits);
        }
        out.text += writeIndent(depth);
        out.text += '</array>\n';
      }
      break;
    }
    case 'String':
      out.text += writeIndent(depth);
      out.text += '<string>';
      out.text += escapeXmlText(node.kind.text);
      out.text += '</string>\n';
      break;
    case 'Integer':
      out.text += writeIndent(depth);
      out.text += `<integer>${node.kind.value}</integer>\n`;
      break;
    case 'Real':
      out.text += writeIndent(depth);
      out.text += `<real>${renderReal(node.kind.real)}</real>\n`;
      break;
    case 'Boolean':
      out.text += writeIndent(depth);
      out.text += node.kind.value ? '<true/>\n' : '<false/>\n';
      break;
    case 'Date': {
      out.text += writeIndent(depth);
      const fields = wholeSecondDate(node.kind.seconds);
      out.text += `<date>${renderDate(fields)}</date>\n`;
      break;
    }
    case 'Data':
      out.text += writeIndent(depth);
      out.text += '<data>';
      out.text += encodeBase64Wrapped(node.kind.bytes, depth);
      out.text += '</data>\n';
      break;
    case 'Uid':
      throw new MaterializationFailure('Unrepresentable', { path: node.path, valueKind: 'Integer' });
  }
  items.push({ path: node.path, target: rank.value });
  rank.value += 1;
  if (out.text.length > limits.maxOutputBytes) {
    throw new MaterializationFailure('ResourceLimit', { reason: 'output-bytes' });
  }
}

function writeIndent(depth: number): string {
  return '    '.repeat(depth);
}

/** Escapes XML text content (RFC 0013 §4.9, §10.1; materialization.rs:1221-1231). */
function escapeXmlText(text: string): string {
  let out = '';
  for (const character of text) {
    switch (character) {
      case '&':
        out += '&amp;';
        break;
      case '<':
        out += '&lt;';
        break;
      case '>':
        out += '&gt;';
        break;
      case '\r':
        out += '&#13;';
        break;
      default:
        out += character;
        break;
    }
  }
  return out;
}

/** Deterministic shortest-round-trip decimal spelling of one real (materialization.rs:1235-1248). */
function renderReal(real: PlistReal): string {
  const value = real.asF64();
  if (Number.isNaN(value)) {
    return 'nan';
  }
  if (!Number.isFinite(value)) {
    return Object.is(value, -Infinity) ? '-inf' : 'inf';
  }
  return String(value);
}

/** Whole-second XML date spelling (materialization.rs:1269-1275). */
function renderDate(fields: { year: number; month: number; day: number; hour: number; minute: number; second: number }): string {
  const sign = fields.year < 0 ? '-' : '';
  const year = Math.abs(fields.year).toString().padStart(4, '0');
  const pad = (value: number) => String(value).padStart(2, '0');
  return `${sign}${year}-${pad(fields.month)}-${pad(fields.day)}T${pad(fields.hour)}:${pad(fields.minute)}:${pad(fields.second)}Z`;
}

/** Canonical standard-alphabet base64 wrapped at `76 - 8 * depth` per line (materialization.rs:1338-1369). */
function encodeBase64Wrapped(bytes: Uint8Array, depth: number): string {
  const ALPHABET = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/';
  const budget = Math.max(76 - 8 * depth, 1);
  let out = '';
  let line = 0;
  for (let at = 0; at < bytes.length; at += 3) {
    const first = bytes[at];
    const second = at + 1 < bytes.length ? bytes[at + 1] : 0;
    const third = at + 2 < bytes.length ? bytes[at + 2] : 0;
    if (line + 4 > budget && line > 0) {
      out += '\n';
      out += writeIndent(depth);
      line = 0;
    }
    out += ALPHABET[first >> 2];
    out += ALPHABET[((first & 0x03) << 4) | (second >> 4)];
    out += at + 1 < bytes.length ? ALPHABET[((second & 0x0f) << 2) | (third >> 6)] : '=';
    out += at + 2 < bytes.length ? ALPHABET[third & 0x3f] : '=';
    line += 4;
  }
  return out;
}

