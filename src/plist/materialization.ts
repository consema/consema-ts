// Record validation (materialization.rs:306-655)
// ---------------------------------------------------------------------------

function validateRecord(value: PortableValue, request: MaterializationRequest, analyzed: ValuePath[]): Record {
  analyzed.push(ValuePath.root());
  const recordField = objectField(value, 'record');
  if (recordField === undefined || recordField.kind !== 'String' || recordField.value !== VALUE_TREE_RECORD) {
    throw new MaterializationFailure('InvalidRequest', { reason: 'input record is not plist.value-tree@1' });
  }
  let policy = false;
  const policyField = objectField(value, 'truncate_policy');
  if (policyField !== undefined) {
    if (policyField.kind !== 'String' || policyField.value !== TRUNCATE_POLICY) {
      throw new MaterializationFailure('InvalidRequest', { reason: 'unsupported truncate policy' });
    }
    policy = true;
  }
  const rootField = objectField(value, 'root');
  if (rootField === undefined) {
    throw new MaterializationFailure('InvalidRequest', { reason: 'missing record field: root' });
  }
  const rootPath = ValuePath.root().child({ kind: 'ObjectValue', name: 'root' });
  const validator = new Validator(request.limits());
  const root = validateValueNode(rootField, rootPath, validator, analyzed, 0);
  return { root, policy };
}

class Validator {
  readonly #limits: MaterializationLimits;
  nodes = 0;

  constructor(limits: MaterializationLimits) {
    this.#limits = limits;
  }

  step(): void {
    this.nodes += 1;
    if (this.nodes > this.#limits.maxInputNodes) {
      throw new MaterializationFailure('ResourceLimit', { reason: 'input-nodes' });
    }
  }

  limits(): MaterializationLimits {
    return this.#limits;
  }
}

/** Validates one value of the record and its descendants (materialization.rs:438-655). */
function validateValueNode(
  value: PortableValue,
  path: ValuePath,
  validator: Validator,
  analyzed: ValuePath[],
  depth: number,
): ValueNode {
  validator.step();
  analyzed.push(path);
  const limits = validator.limits();
  let kind: ValueKind;
  if (value.kind === 'EntryMapping') {
    if (depth + 1 > limits.maxDepth) {
      throw new MaterializationFailure('ResourceLimit', { reason: 'input-depth' });
    }
    const entries: DictEntry[] = [];
    for (let ordinal = 0; ordinal < value.entries.length; ordinal++) {
      const entry = value.entries[ordinal];
      if (entry.key.kind !== 'String') {
        throw new MaterializationFailure('Unrepresentable', {
          path: path.child({ kind: 'EntryKey', index: BigInt(ordinal) }),
          valueKind: entry.key.kind,
        });
      }
      const child = validateValueNode(
        entry.value,
        path.child({ kind: 'EntryValue', index: BigInt(ordinal) }),
        validator,
        analyzed,
        depth + 1,
      );
      entries.push({ key: entry.key.value, keyPath: path.child({ kind: 'EntryKey', index: BigInt(ordinal) }), value: child });
    }
    kind = { kind: 'Dict', entries };
  } else if (value.kind === 'Sequence') {
    if (depth + 1 > limits.maxDepth) {
      throw new MaterializationFailure('ResourceLimit', { reason: 'input-depth' });
    }
    const elements: ValueNode[] = [];
    for (let index = 0; index < value.items.length; index++) {
      elements.push(
        validateValueNode(
          value.items[index],
          path.child({ kind: 'SequenceElement', index: BigInt(index) }),
          validator,
          analyzed,
          depth + 1,
        ),
      );
    }
    kind = { kind: 'Array', elements };
  } else if (value.kind === 'String') {
    if (value.value.length > limits.maxOutputBytes) {
      throw new MaterializationFailure('ResourceLimit', { reason: 'output-bytes' });
    }
    kind = { kind: 'String', text: value.value };
  } else if (value.kind === 'Integer') {
    if (value.value > 0x7fffffffffffffffn || value.value < -0x8000000000000000n) {
      throw new MaterializationFailure('Unrepresentable', { path, valueKind: 'Integer' });
    }
    kind = { kind: 'Integer', value: value.value };
  } else if (value.kind === 'BinaryFloat32') {
    kind = { kind: 'Real', real: PlistReal.fromBits('Float32', BigInt(value.bits)) };
  } else if (value.kind === 'BinaryFloat64') {
    kind = { kind: 'Real', real: PlistReal.fromBits('Float64', value.bits) };
  } else if (value.kind === 'Decimal') {
    const converted = decimalToF64(value.coefficient, value.exponent);
    if (converted === null) {
      throw new MaterializationFailure('Unrepresentable', { path, valueKind: 'Decimal' });
    }
    kind = { kind: 'Real', real: PlistReal.double(converted) };
  } else if (value.kind === 'Boolean') {
    kind = { kind: 'Boolean', value: value.value };
  } else if (value.kind === 'Bytes') {
    if (value.value.length > limits.maxOutputBytes) {
      throw new MaterializationFailure('ResourceLimit', { reason: 'output-bytes' });
    }
    kind = { kind: 'Data', bytes: value.value };
  } else if (value.kind === 'Object') {
    if (objectField(value, 'kind') !== undefined) {
      // The explicit `{kind, ...}` record spelling is not the
      // `plist.value-tree@1` record (RFC 0013 §9).
      throw new MaterializationFailure('Unrepresentable', { path, valueKind: 'Object' });
    }
    const epoch = objectField(value, 'epoch');
    const seconds = objectField(value, 'seconds');
    if (epoch !== undefined && seconds !== undefined) {
      if (epoch.kind !== 'String' || epoch.value !== PLIST_EPOCH_SPELLING) {
        throw new MaterializationFailure('InvalidRequest', {
          reason: 'date epoch is not 2001-01-01T00:00:00Z',
        });
      }
      let secondsValue: number;
      if (seconds.kind === 'BinaryFloat64') {
        secondsValue = float64FromBits(seconds.bits);
      } else if (seconds.kind === 'Decimal') {
        const converted = decimalToF64(seconds.coefficient, seconds.exponent);
        if (converted === null) {
          throw new MaterializationFailure('Unrepresentable', { path, valueKind: 'Date' });
        }
        secondsValue = converted;
      } else {
        throw new MaterializationFailure('Unrepresentable', { path, valueKind: 'Date' });
      }
      if (!Number.isFinite(secondsValue)) {
        throw new MaterializationFailure('Unrepresentable', { path, valueKind: 'Date' });
      }
      kind = { kind: 'Date', seconds: secondsValue };
    } else if (objectField(value, 'uid') !== undefined) {
      const uid = objectField(value, 'uid')!;
      if (uid.kind !== 'Integer' || uid.value < 0n || uid.value > 0xffffffffn) {
        throw new MaterializationFailure('Unrepresentable', {
          path: path.child({ kind: 'ObjectValue', name: 'uid' }),
          valueKind: uid.kind,
        });
      }
      kind = { kind: 'Uid', value: Number(uid.value) };
    } else if (objectField(value, 'hex') !== undefined) {
      const hex = objectField(value, 'hex')!;
      if (hex.kind !== 'String') {
        throw new MaterializationFailure('Unrepresentable', {
          path: path.child({ kind: 'ObjectValue', name: 'hex' }),
          valueKind: hex.kind,
        });
      }
      if (hex.value.length / 2 > limits.maxOutputBytes) {
        throw new MaterializationFailure('ResourceLimit', { reason: 'output-bytes' });
      }
      const bytes = decodeHex(hex.value);
      if (bytes === null) {
        throw new MaterializationFailure('Unrepresentable', {
          path: path.child({ kind: 'ObjectValue', name: 'hex' }),
          valueKind: 'String',
        });
      }
      kind = { kind: 'Data', bytes };
    } else {
      // A dictionary spelled as an ordered JSON object.
      if (depth + 1 > limits.maxDepth) {
        throw new MaterializationFailure('ResourceLimit', { reason: 'input-depth' });
      }
      const entries: DictEntry[] = [];
      for (let ordinal = 0; ordinal < value.entries.length; ordinal++) {
        const entry = value.entries[ordinal];
        const child = validateValueNode(
          entry.value,
          path.child({ kind: 'EntryValue', index: BigInt(ordinal) }),
          validator,
          analyzed,
          depth + 1,
        );
        entries.push({ key: entry.key, keyPath: path.child({ kind: 'EntryKey', index: BigInt(ordinal) }), value: child });
      }
      kind = { kind: 'Dict', entries };
    }
  } else {
    throw new MaterializationFailure('Unrepresentable', { path, valueKind: value.kind });
  }
  return { path, kind };
}

function objectField(value: PortableValue, name: string): PortableValue | undefined {
  if (value.kind !== 'Object') {
    return undefined;
  }
  return value.entries.find((entry) => entry.key === name)?.value;
}

/** Converts one exact decimal to its double value (materialization.rs:665-679). */
function decimalToF64(coefficient: bigint, exponent: bigint): number | null {
  if (coefficient > BigInt(Number.MAX_SAFE_INTEGER) || coefficient < -BigInt(Number.MAX_SAFE_INTEGER)) {
    return null;
  }
  if (exponent > 308n || exponent < -308n) {
    return null;
  }
  let value = Number(coefficient);
  if (exponent > 0n) {
    value *= 10 ** Number(exponent);
  } else if (exponent < 0n) {
    value /= 10 ** Number(-exponent);
  }
  return value;
}

/** Strictly decodes one even-length hex string (materialization.rs:682-700). */
function decodeHex(text: string): Uint8Array | null {
  if (text.length % 2 !== 0 || !/^[0-9a-fA-F]*$/.test(text)) {
    return null;
  }
  const bytes = new Uint8Array(text.length / 2);
  for (let index = 0; index < bytes.length; index++) {
    bytes[index] = (hexDigit(text.charCodeAt(index * 2)) << 4) | hexDigit(text.charCodeAt(index * 2 + 1));
  }
  return bytes;
}

function hexDigit(code: number): number {
  if (code >= 0x30 && code <= 0x39) return code - 0x30;
  if (code >= 0x61 && code <= 0x66) return code - 0x61 + 10;
  return code - 0x41 + 10;
}

