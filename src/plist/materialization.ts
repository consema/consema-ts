// Provenance (materialization.rs:1619-1764)
// ---------------------------------------------------------------------------

function buildProvenance(
  items: InputItem[],
  document: PlistDocument,
  style: Style,
  limits: MaterializationLimits,
): MaterializationProvenanceMap {
  const authority = document.authorityInternal();
  const identity = document.snapshotIdentity();
  const origins: MaterializedOrigin[] = [];
  if (style === 'Binary') {
    const facts = document.binaryFacts();
    if (facts === null) {
      throw new MaterializationFailure('FormationFailed');
    }
    for (const item of items) {
      const fact = facts.objects()[item.target];
      if (fact === undefined) {
        throw new MaterializationFailure('FormationFailed');
      }
      origins.push(
        new MaterializedOrigin(
          identity,
          authority.nodeRef(BigInt(fact.index()), 'PlistValue'),
          fact.span(),
          'Direct',
        ),
      );
    }
  } else {
    const spans = xmlValueSpans(document);
    for (const item of items) {
      const span = spans[item.target];
      if (span === undefined) {
        throw new MaterializationFailure('FormationFailed');
      }
      origins.push(
        new MaterializedOrigin(
          identity,
          authority.nodeRef(BigInt(item.target), 'PlistValue'),
          span,
          'Direct',
        ),
      );
    }
  }
  const entries = items.map(
    (item, index) =>
      new MaterializationProvenanceEntry(
        { kind: 'Value', path: item.path },
        [origins[index]],
      ),
  );
  return MaterializationProvenanceMap.create(entries, identity, limits);
}

/** Reconstructs the value element spans of one reparsed XML document, in arena (close-tag) order. */
function xmlValueSpans(document: PlistDocument): Span[] {
  const pieces = document.losslessStructuralIndex()?.pieces();
  const kinds = document.losslessSyntaxKinds();
  if (pieces === undefined || kinds === null) {
    throw new MaterializationFailure('FormationFailed');
  }
  const source = document.source().bytes();
  const authority = document.authorityInternal();
  const spans: Span[] = [];
  const stack: Array<{ readonly start: number; readonly kind: PlistSyntaxKind }> = [];
  const openKinds = new Set<PlistSyntaxKind>([
    'dict-open',
    'array-open',
    'string-open',
    'integer-open',
    'real-open',
    'date-open',
    'data-open',
  ]);
  const closeKinds = new Set<PlistSyntaxKind>([
    'dict-close',
    'array-close',
    'string-close',
    'integer-close',
    'real-close',
    'date-close',
    'data-close',
  ]);
  for (let index = 0; index < pieces.length; index++) {
    const span = pieces[index].span();
    const kind = kinds[index];
    if (openKinds.has(kind)) {
      const raw = source.slice(span.startByte(), span.endByte());
      if (raw.length !== 1 || raw[0] !== 0x3e /* > */) {
        stack.push({ start: span.startByte(), kind });
      }
    } else if (closeKinds.has(kind)) {
      const open = stack.pop();
      if (open === undefined) {
        throw new MaterializationFailure('FormationFailed');
      }
      spans.push(authority.span(open.start, span.endByte()));
    } else if (kind === 'true' || kind === 'false') {
      const raw = source.slice(span.startByte(), span.endByte());
      const rawText = new TextDecoder().decode(raw);
      if (rawText.startsWith('</') || rawText === '/>') {
        const open = stack.pop();
        if (open === undefined || open.kind !== kind) {
          throw new MaterializationFailure('FormationFailed');
        }
        spans.push(authority.span(open.start, span.endByte()));
      } else if (rawText !== '>') {
        stack.push({ start: span.startByte(), kind });
      }
    }
  }
  if (stack.length > 0) {
    throw new MaterializationFailure('FormationFailed');
  }
  return spans;
}

function bitsOfFloat64(value: number): bigint {
  const view = new DataView(new ArrayBuffer(8));
  view.setFloat64(0, value, false);
  return view.getBigUint64(0, false);
}

function float64FromBits(bits: bigint): number {
  const view = new DataView(new ArrayBuffer(8));
  view.setBigUint64(0, bits & 0xffffffffffffffffn, false);
  return view.getFloat64(0, false);
}

/** Lowercase hex of one byte sequence (deduplication key material only). */
function hexOf(bytes: Uint8Array): string {
  let out = '';
  for (const byte of bytes) {
    out += byte.toString(16).padStart(2, '0');
  }
  return out;
}
