/** Builds the promised native document, applying the XML expressibility boundary. */
function buildNative(
  record: Record,
  style: Style,
  limits: MaterializationLimits,
): { readonly document: PlistNativeDocument; readonly events: Diagnostic[]; readonly transformed: boolean } {
  const builder = new PlistDocumentBuilder({
    maxObjects: limits.maxInputNodes,
    maxContainerDepth: limits.maxDepth,
  });
  const events: Diagnostic[] = [];
  const transformed = { value: false };
  const root = buildValue(builder, record.root, style, record.policy, { events, transformed }, limits);
  try {
    const document = builder.build(root);
    return { document, events, transformed: transformed.value };
  } catch (error) {
    if (error instanceof PlistArenaError) {
      throw new MaterializationFailure('ResourceLimit', { reason: 'input-nodes' });
    }
    throw error;
  }
}

function buildValue(
  builder: PlistDocumentBuilder,
  node: ValueNode,
  style: Style,
  policy: boolean,
  state: { readonly events: Diagnostic[]; readonly transformed: { value: boolean } },
  limits: MaterializationLimits,
): number {
  switch (node.kind.kind) {
    case 'Dict': {
      const entries: Array<{ readonly key: string; readonly value: number }> = [];
      for (const entry of node.kind.entries) {
        if (style === 'Xml' && !isXmlText(entry.key)) {
          throw new MaterializationFailure('Unrepresentable', {
            path: entry.keyPath,
            valueKind: 'String',
          });
        }
        const value = buildValue(builder, entry.value, style, policy, state, limits);
        entries.push({ key: entry.key, value });
      }
      return builder.add({ kind: 'Dict', entries: Object.freeze(entries) });
    }
    case 'Array': {
      const elements: number[] = [];
      for (const element of node.kind.elements) {
        elements.push(buildValue(builder, element, style, policy, state, limits));
      }
      return builder.add({ kind: 'Array', elements: Object.freeze(elements) });
    }
    case 'String': {
      if (style === 'Xml' && (classifySurrogates(node.kind.text) === 'UnpairedSurrogate' || !isXmlText(node.kind.text))) {
        throw new MaterializationFailure('Unrepresentable', { path: node.path, valueKind: 'String' });
      }
      return builder.add(plistStringValue(node.kind.text));
    }
    case 'Integer':
      return builder.add(plistIntegerValue(node.kind.value));
    case 'Real': {
      if (style === 'Xml') {
        if (node.kind.real.width() === 'Float32') {
          throw new MaterializationFailure('Unrepresentable', { path: node.path, valueKind: 'BinaryFloat32' });
        }
        if (!realExpressible(node.kind.real)) {
          throw new MaterializationFailure('Unrepresentable', { path: node.path, valueKind: 'BinaryFloat64' });
        }
      }
      return builder.add(plistRealValue(node.kind.real));
    }
    case 'Boolean':
      return builder.add(plistBooleanValue(node.kind.value));
    case 'Date': {
      if (style === 'Xml') {
        const nodeCopy = node.kind;
        if (bitsOfFloat64(nodeCopy.seconds) === NEGATIVE_ZERO_BITS) {
          throw new MaterializationFailure('Unrepresentable', { path: node.path, valueKind: 'Date' });
        }
        try {
          wholeSecondDate(nodeCopy.seconds);
        } catch (error) {
          if (error instanceof DateRangeError && error.kind === 'FractionalSeconds') {
            if (!policy) {
              throw new MaterializationFailure('Unrepresentable', { path: node.path, valueKind: 'Date' });
            }
            const original = nodeCopy.seconds;
            const truncated = Math.trunc(original);
            if (bitsOfFloat64(truncated) === NEGATIVE_ZERO_BITS || wholeSecondDateSafe(truncated) === null) {
              throw new MaterializationFailure('Unrepresentable', { path: node.path, valueKind: 'Date' });
            }
            nodeCopy.seconds = truncated;
            state.events.push(
              diagnostic(FRACTIONAL_DATE_CODE, 'Materialization', 'Warning', null, BigInt(state.events.length), {
                arguments: [
                  ['path', renderPath(node.path)],
                  ['seconds', String(original)],
                ],
              }),
            );
            state.transformed.value = true;
          } else {
            throw new MaterializationFailure('Unrepresentable', { path: node.path, valueKind: 'Date' });
          }
        }
      }
      return builder.add(plistDateValue(node.kind.seconds));
    }
    case 'Data':
      return builder.add(plistDataValue(node.kind.bytes));
    case 'Uid': {
      if (style === 'Xml') {
        throw new MaterializationFailure('Unrepresentable', { path: node.path, valueKind: 'Integer' });
      }
      return builder.add(plistUidValue(node.kind.value));
    }
  }
}

/** Stable path rendering for diagnostic arguments (materialization.rs:891-917). */
function renderPath(path: ValuePath): string {
  let out = '';
  for (const segment of path.segments()) {
    switch (segment.kind) {
      case 'ObjectValue':
        out += `/${segment.name}`;
        break;
      case 'SequenceElement':
        out += `[${segment.index}]`;
        break;
      case 'EntryKey':
        out += `[key ${segment.index}]`;
        break;
      case 'EntryValue':
        out += `[value ${segment.index}]`;
        break;
    }
  }
  return out;
}

/** Whether the exact bits of one real survive the XML spelling (materialization.rs:1253-1265). */
function realExpressible(real: PlistReal): boolean {
  const value = real.asF64();
  if (Number.isNaN(value)) {
    return bitsOfFloat64(value) === bitsOfFloat64(Number.NaN);
  }
  if (!Number.isFinite(value)) {
    return true;
  }
  return bitsOfFloat64(Number(value.toString())) === bitsOfFloat64(value);
}

/** XML 1.0 `Char` production (materialization.rs:1372-1379). */
function isXmlCharCode(code: number): boolean {
  return (
    code === 0x09 ||
    code === 0x0a ||
    code === 0x0d ||
    (code >= 0x20 && code <= 0xd7ff) ||
    (code >= 0xe000 && code <= 0xfffd) ||
    (code >= 0x10000 && code <= 0x10ffff)
  );
}

/** Whether every scalar of one UTF-16 sequence is an XML 1.0 character (materialization.rs:1383-1407). */
function isXmlText(text: string): boolean {
  return classifySurrogates(text) === 'WellFormedUnicode' && [...text].every((c) => isXmlCharCode(c.codePointAt(0)!));
}

function classifySurrogates(text: string): 'WellFormedUnicode' | 'UnpairedSurrogate' {
  for (let index = 0; index < text.length; index++) {
    const unit = text.charCodeAt(index);
    if (unit >= 0xd800 && unit <= 0xdbff) {
      const low = index + 1 < text.length ? text.charCodeAt(index + 1) : 0;
      if (low >= 0xdc00 && low <= 0xdfff) {
        index += 1;
      } else {
        return 'UnpairedSurrogate';
      }
    } else if (unit >= 0xdc00 && unit <= 0xdfff) {
      return 'UnpairedSurrogate';
    }
  }
  return 'WellFormedUnicode';
}

class DateRangeError extends Error {
  readonly kind: 'FractionalSeconds' | 'YearOutOfRange';
  constructor(kind: 'FractionalSeconds' | 'YearOutOfRange') {
    super(`date range: ${kind}`);
    this.kind = kind;
  }
}

/** Decomposes exact plist-epoch seconds into XML calendar fields (materialization.rs:1292-1313). */
function wholeSecondDate(seconds: number): { year: number; month: number; day: number; hour: number; minute: number; second: number } {
  if (seconds % 1 !== 0) {
    throw new DateRangeError('FractionalSeconds');
  }
  const result = wholeSecondDateSafe(seconds);
  if (result === null) {
    throw new DateRangeError('YearOutOfRange');
  }
  return result;
}

function wholeSecondDateSafe(
  seconds: number,
): { year: number; month: number; day: number; hour: number; minute: number; second: number } | null {
  const unix = seconds + PLIST_EPOCH_OFFSET_UNIX;
  if (Math.abs(unix) >= EXACT_UNIX_SECONDS_BOUND) {
    return null;
  }
  const unixInt = Math.trunc(unix);
  const days = Math.floor(unixInt / 86400);
  const secondsOfDay = unixInt % 86400;
  const civil = civilFromDays(days);
  if (Math.abs(civil.year) > 0xffffffff) {
    return null;
  }
  return {
    year: civil.year,
    month: civil.month,
    day: civil.day,
    hour: Math.floor(secondsOfDay / 3600),
    minute: Math.floor((secondsOfDay % 3600) / 60),
    second: secondsOfDay % 60,
  };
}

/** Proleptic Gregorian calendar date of `days` since the Unix epoch (materialization.rs:1317-1330). */
function civilFromDays(days: number): { year: number; month: number; day: number } {
  const z = days + 719468;
  const era = z >= 0 ? z : z - 146096;
  const eraFloor = Math.floor(era / 146097);
  const dayOfEra = z - eraFloor * 146097;
  const yearOfEra = Math.floor((dayOfEra - Math.floor(dayOfEra / 1460) + Math.floor(dayOfEra / 36524) - Math.floor(dayOfEra / 146096)) / 365);
  let year = yearOfEra + eraFloor * 400;
  const dayOfYear = dayOfEra - (365 * yearOfEra + Math.floor(yearOfEra / 4) - Math.floor(yearOfEra / 100));
  const monthPrime = Math.floor((5 * dayOfYear + 2) / 153);
  const day = dayOfYear - Math.floor((153 * monthPrime + 2) / 5) + 1;
  const month = monthPrime + (monthPrime < 10 ? 3 : -9);
  year = month <= 2 ? year + 1 : year;
  return { year, month, day };
}

