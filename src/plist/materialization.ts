/** Materializes one `plist.value-tree@1` record into a new canonical plist document (RFC 0013 §10). */
export function materialize(
  value: PortableValue,
  request: MaterializationRequest,
): MaterializationResult<PlistDocument> {
  const analyzed: ValuePath[] = [];
  try {
    return { kind: 'Complete', value: materializeComplete(value, request, analyzed) };
  } catch (error) {
    if (!(error instanceof MaterializationFailure)) {
      throw error;
    }
    return {
      kind: 'Failed',
      value: new FailedMaterializationAttempt(
        error,
        new MaterializationReport([], request.limits()),
        analyzed,
      ),
    };
  }
}

/** Maps one plist-family materialization failure to its stable code (materialization.rs:78-94). */
export function plistMaterializationFailureCode(failure: MaterializationFailure): string {
  switch (failure.kind) {
    case 'Unrepresentable':
      return failure.valueKind === 'Date'
        ? FRACTIONAL_DATE_CODE
        : 'plist.materialization.unrepresentable@1';
    case 'ResourceLimit':
      return 'plist.materialization.resource-limit@1';
    default:
      return failure.code;
  }
}

function materializeComplete(
  value: PortableValue,
  request: MaterializationRequest,
  analyzed: ValuePath[],
): CompleteMaterialization<PlistDocument> {
  const style = validateRequest(request);
  const limits = request.limits();
  const record = validateRecord(value, request, analyzed);
  const { document: native, events, transformed } = buildNative(record, style, limits);
  const { bytes, items } = serialize(record, style, limits);
  const profile = style === 'Xml' ? ('XmlV1' as const) : ('BinaryV1' as const);
  let document: PlistDocument;
  try {
    document = parse(bytes, profile, { kind: 'ProfileDefault' }, parseLimitsFor(limits));
  } catch {
    throw new MaterializationFailure('FormationFailed');
  }
  if (document.formationStatus() !== 'Complete' || document.document() === null) {
    throw new MaterializationFailure('FormationFailed');
  }
  const nativeDocument = document.document();
  if (nativeDocument === null || !nativeDocument.equals(native)) {
    throw new MaterializationFailure('FormationFailed');
  }
  const report = new MaterializationReport(events, limits);
  const provenance = buildProvenance(items, document, style, limits);
  const fidelity: MaterializationFidelity = transformed ? 'Transformed' : 'Exact';
  return new CompleteMaterialization(document, fidelity, report, provenance);
}

/** Validates the request against the frozen style contracts (materialization.rs:236-266). */
function validateRequest(request: MaterializationRequest): Style {
  const profile = request.targetProfile();
  const style = request.style();
  let selected: Style;
  if (profile.id() === 'plist.xml' && profile.version() === 1 && style.id() === STYLE_XML && style.version() === 1) {
    selected = 'Xml';
  } else if (profile.id() === 'plist.binary' && profile.version() === 1 && style.id() === STYLE_BINARY && style.version() === 1) {
    selected = 'Binary';
  } else if ((profile.id() !== 'plist.xml' && profile.id() !== 'plist.binary') || profile.version() !== 1) {
    throw new MaterializationFailure('UnsupportedProfile');
  } else {
    throw new MaterializationFailure('UnsupportedStyle');
  }
  if (selected === 'Xml') {
    if (request.encoding().kind !== 'Utf8') {
      throw new MaterializationFailure('UnsupportedEncoding');
    }
    if (request.newline() !== 'Lf') {
      throw new MaterializationFailure('UnsupportedNewline');
    }
  } else {
    if (request.encoding().kind !== 'Binary') {
      throw new MaterializationFailure('UnsupportedEncoding');
    }
    if (request.newline() !== 'None') {
      throw new MaterializationFailure('UnsupportedNewline');
    }
  }
  return selected;
}

/** Parse limits for the closure reparse, derived from the request (materialization.rs:274-304). */
function parseLimitsFor(limits: MaterializationLimits): PlistParseLimits {
  return {
    ...DEFAULT_PLIST_PARSE_LIMITS,
    common: {
      maxSourceBytes: limits.maxOutputBytes,
      maxNestingDepth: limits.maxDepth + 2,
      maxTokenCount: limits.maxOutputBytes,
      maxNodeCount: limits.maxInputNodes,
      maxDiagnostics: limits.maxReportEntries,
    },
    maxDecodedUtf8Bytes: limits.maxOutputBytes * 3,
    maxDecodedScalars: limits.maxOutputBytes,
    maxObjectCount: limits.maxInputNodes * 2,
    maxContainerDepth: limits.maxDepth,
    maxDictEntries: limits.maxInputNodes,
    maxArrayElements: limits.maxInputNodes,
    maxDuplicateKeyGroupMembers: limits.maxInputNodes,
    maxStringCodeUnits: limits.maxOutputBytes,
    maxDataBytes: limits.maxOutputBytes,
    maxUidCount: limits.maxInputNodes,
    maxExtendedSizeIntegers: limits.maxInputNodes * 2,
    maxExtendedSizeValue: limits.maxInputNodes,
    maxOffsetIntSize: 8,
    maxObjectRefSize: 8,
    maxOffsetTableBytes: limits.maxOutputBytes * 8,
    maxSyntaxPieces: limits.maxOutputBytes,
    maxBinaryFacts: limits.maxOutputBytes * 16,
    maxConversionNodes: limits.maxInputNodes,
    maxReportEvents: limits.maxReportEntries,
    maxRecoveryRegions: limits.maxReportEntries,
  };
}

