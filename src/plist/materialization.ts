/** Content key of one scalar object (materialization.rs:946-992). */
type ScalarKey =
  | { readonly kind: 'String'; readonly text: string }
  | { readonly kind: 'Integer'; readonly value: bigint }
  | { readonly kind: 'Real'; readonly bits: bigint; readonly width: 'Float64' | 'Float32' }
  | { readonly kind: 'Boolean'; readonly value: boolean }
  | { readonly kind: 'Date'; readonly bits: bigint }
  | { readonly kind: 'Data'; readonly bytes: Uint8Array }
  | { readonly kind: 'Uid'; readonly value: number };

function scalarKeyOf(node: ValueNode): ScalarKey {
  switch (node.kind.kind) {
    case 'String':
      return { kind: 'String', text: node.kind.text };
    case 'Integer':
      return { kind: 'Integer', value: node.kind.value };
    case 'Real':
      return { kind: 'Real', bits: node.kind.real.bits(), width: node.kind.real.width() };
    case 'Boolean':
      return { kind: 'Boolean', value: node.kind.value };
    case 'Date':
      return { kind: 'Date', bits: bitsOfFloat64(node.kind.seconds) };
    case 'Data':
      return { kind: 'Data', bytes: node.kind.bytes };
    case 'Uid':
      return { kind: 'Uid', value: node.kind.value };
    case 'Dict':
    case 'Array':
      throw new Error('internal: containers are planned before their children');
  }
}

/** Whether this scalar participates in first-occurrence deduplication (materialization.rs:984-992). */
function deduplicates(key: ScalarKey): boolean {
  return key.kind === 'String' || key.kind === 'Integer' || key.kind === 'Real' || key.kind === 'Date' || key.kind === 'Data';
}

type PlannedObject =
  | { readonly kind: 'Dict'; keys: number[]; values: number[] }
  | { readonly kind: 'Array'; elements: number[] }
  | { readonly kind: 'Scalar'; readonly key: ScalarKey };

/** Plans the document-ordered binary object table (materialization.rs:1011-1096). */
function planBinary(root: ValueNode): { readonly objects: PlannedObject[]; readonly items: InputItem[] } {
  const objects: PlannedObject[] = [];
  const items: InputItem[] = [];
  const cache = new Map<string, number>();
  const scalarKeyId = (key: ScalarKey): string => {
    switch (key.kind) {
      case 'String':
        return `s:${key.text}`;
      case 'Integer':
        return `i:${key.value}`;
      case 'Real':
        return `r:${key.width}:${key.bits}`;
      case 'Boolean':
        return `b:${key.value}`;
      case 'Date':
        return `d:${key.bits}`;
      case 'Data':
        return `x:${hexOf(key.bytes)}`;
      case 'Uid':
        return `u:${key.value}`;
    }
  };
  const planNode = (node: ValueNode): number => {
    switch (node.kind.kind) {
      case 'Dict': {
        const index = objects.length;
        objects.push({ kind: 'Dict', keys: [], values: [] });
        items.push({ path: node.path, target: index });
        const keyRefs: number[] = [];
        for (const entry of node.kind.entries) {
          const key = scalarKeyOf({ path: entry.keyPath, kind: { kind: 'String', text: entry.key } });
          const id = scalarKeyId(key);
          let keyIndex = cache.get(id);
          if (keyIndex === undefined) {
            keyIndex = objects.length;
            objects.push({ kind: 'Scalar', key });
            cache.set(id, keyIndex);
          }
          keyRefs.push(keyIndex);
        }
        const valueRefs = node.kind.entries.map((entry) => planNode(entry.value));
        (objects[index] as { kind: 'Dict'; keys: number[]; values: number[] }).keys = keyRefs;
        (objects[index] as { kind: 'Dict'; keys: number[]; values: number[] }).values = valueRefs;
        return index;
      }
      case 'Array': {
        const index = objects.length;
        objects.push({ kind: 'Array', elements: [] });
        items.push({ path: node.path, target: index });
        const elements = node.kind.elements.map((element) => planNode(element));
        (objects[index] as { kind: 'Array'; elements: number[] }).elements = elements;
        return index;
      }
      default: {
        const key = scalarKeyOf(node);
        if (deduplicates(key)) {
          const id = scalarKeyId(key);
          const cached = cache.get(id);
          if (cached !== undefined) {
            items.push({ path: node.path, target: cached });
            return cached;
          }
          const index = objects.length;
          objects.push({ kind: 'Scalar', key });
          cache.set(id, index);
          items.push({ path: node.path, target: index });
          return index;
        }
        const index = objects.length;
        objects.push({ kind: 'Scalar', key });
        items.push({ path: node.path, target: index });
        return index;
      }
    }
  };
  planNode(root);
  return { objects, items };
}

function serializeBinary(record: Record, limits: MaterializationLimits): { readonly bytes: Uint8Array; readonly items: InputItem[] } {
  const plan = planBinary(record.root);
  const numObjects = plan.objects.length;
  const refSize = refSizeFor(numObjects);
  const chunks: Uint8Array[] = [new TextEncoder().encode('bplist00')];
  const offsets: number[] = [];
  let total = 8;
  for (const object of plan.objects) {
    offsets.push(total);
    const bytes = writePlannedObject(object, refSize);
    total += bytes.length;
    if (total > limits.maxOutputBytes) {
      throw new MaterializationFailure('ResourceLimit', { reason: 'output-bytes' });
    }
    chunks.push(bytes);
  }
  const offsetTableOffset = total;
  const offsetIntSize = refSizeFor(offsetTableOffset);
  const table = new Uint8Array(numObjects * offsetIntSize);
  for (let index = 0; index < numObjects; index++) {
    writeBe(table, index * offsetIntSize, BigInt(offsets[index]), offsetIntSize);
  }
  chunks.push(table);
  const trailer = new Uint8Array(32);
  trailer[5] = 0; // sortVersion
  trailer[6] = offsetIntSize;
  trailer[7] = refSize;
  writeBe(trailer, 8, BigInt(numObjects), 8); // numObjects
  writeBe(trailer, 16, 0n, 8); // topObject: the root value is always object 0
  writeBe(trailer, 24, BigInt(offsetTableOffset), 8); // offsetTableOffset
  chunks.push(trailer);
  const totalLength = chunks.reduce((sum, chunk) => sum + chunk.length, 0);
  const bytes = new Uint8Array(totalLength);
  let at = 0;
  for (const chunk of chunks) {
    bytes.set(chunk, at);
    at += chunk.length;
  }
  return { bytes, items: plan.items };
}

/** Writes one planned object: marker, size, payload, and references (materialization.rs:1456-1520). */
function writePlannedObject(object: PlannedObject, refSize: number): Uint8Array {
  switch (object.kind) {
    case 'Dict': {
      const count = object.keys.length;
      const parts: Uint8Array[] = [sizedMarker(0xd0, count)];
      for (const key of object.keys) {
        parts.push(beBytes(BigInt(key), refSize));
      }
      for (const value of object.values) {
        parts.push(beBytes(BigInt(value), refSize));
      }
      return concat(parts);
    }
    case 'Array': {
      const parts: Uint8Array[] = [sizedMarker(0xa0, object.elements.length)];
      for (const element of object.elements) {
        parts.push(beBytes(BigInt(element), refSize));
      }
      return concat(parts);
    }
    case 'Scalar':
      return writeScalarObject(object.key);
  }
}

function writeScalarObject(key: ScalarKey): Uint8Array {
  switch (key.kind) {
    case 'String': {
      const units = key.text;
      const ascii = [...units].every((c) => c.charCodeAt(0) < 0x80);
      const parts: Uint8Array[] = [sizedMarker(ascii ? 0x50 : 0x60, units.length)];
      if (ascii) {
        parts.push(new TextEncoder().encode(units));
      } else {
        const bytes = new Uint8Array(units.length * 2);
        for (let index = 0; index < units.length; index++) {
          bytes[index * 2] = units.charCodeAt(index) >> 8;
          bytes[index * 2 + 1] = units.charCodeAt(index) & 0xff;
        }
        parts.push(bytes);
      }
      return concat(parts);
    }
    case 'Integer': {
      const width = integerWidth(key.value);
      const parts: Uint8Array[] = [new Uint8Array([0x10 | widthTrailingZeros(width)])];
      parts.push(beBytes(key.value & 0xffffffffffffffffn, width));
      return concat(parts);
    }
    case 'Real': {
      if (key.width === 'Float64') {
        const parts: Uint8Array[] = [new Uint8Array([0x23])];
        parts.push(beBytes(key.bits, 8));
        return concat(parts);
      }
      const parts: Uint8Array[] = [new Uint8Array([0x22])];
      parts.push(beBytes(key.bits, 4));
      return concat(parts);
    }
    case 'Boolean':
      return new Uint8Array([key.value ? 0x09 : 0x08]);
    case 'Date': {
      const parts: Uint8Array[] = [new Uint8Array([0x33])];
      parts.push(beBytes(key.bits, 8));
      return concat(parts);
    }
    case 'Data': {
      const parts: Uint8Array[] = [sizedMarker(0x40, key.bytes.length)];
      parts.push(key.bytes);
      return concat(parts);
    }
    case 'Uid': {
      const width = uidWidth(key.value);
      const parts: Uint8Array[] = [new Uint8Array([0x80 | (width - 1)])];
      parts.push(beBytes(BigInt(key.value), width));
      return concat(parts);
    }
  }
}

/** One sized marker; counts of 15 or more use the extended-size sentinel (materialization.rs:1549-1559). */
function sizedMarker(marker: number, count: number): Uint8Array {
  if (count < 0x0f) {
    return new Uint8Array([marker | count]);
  }
  const width = unsignedWidth(BigInt(count));
  const parts: Uint8Array[] = [new Uint8Array([marker | 0x0f, 0x10 | widthTrailingZeros(width)])];
  parts.push(beBytes(BigInt(count), width));
  return concat(parts);
}

/** Smallest width whose capacity exceeds `max_index` (materialization.rs:1574-1582). */
function refSizeFor(maxIndex: number): number {
  let size = 1;
  let capacity = 256;
  while (maxIndex >= capacity && size < 8) {
    size += 1;
    capacity *= 256;
  }
  return size;
}

/** Minimal marker width for one signed 64-bit integer (materialization.rs:1586-1591). */
function integerWidth(value: bigint): number {
  if (value >= 0n) {
    return unsignedWidth(value);
  }
  return 8;
}

function unsignedWidth(value: bigint): number {
  if (value <= 0xffn) return 1;
  if (value <= 0xffffn) return 2;
  if (value <= 0xffffffffn) return 4;
  return 8;
}

/** Minimal byte width of one unsigned 32-bit UID value (materialization.rs:1607-1617). */
function uidWidth(value: number): number {
  if (value <= 0xff) return 1;
  if (value <= 0xffff) return 2;
  if (value <= 0xffffff) return 3;
  return 4;
}

function widthTrailingZeros(width: number): number {
  switch (width) {
    case 1:
      return 0;
    case 2:
      return 1;
    case 4:
      return 2;
    default:
      return 3;
  }
}

/** Appends one big-endian unsigned value of exactly `width` bytes at `offset`. */
function writeBe(bytes: Uint8Array, offset: number, value: bigint, width: number): void {
  for (let shift = 0; shift < width; shift++) {
    bytes[offset + width - 1 - shift] = Number((value >> BigInt(8 * shift)) & 0xffn);
  }
}

/** One big-endian unsigned value of exactly `width` bytes. */
function beBytes(value: bigint, width: number): Uint8Array {
  const bytes = new Uint8Array(width);
  writeBe(bytes, 0, value, width);
  return bytes;
}

function concat(parts: readonly Uint8Array[]): Uint8Array {
  const total = parts.reduce((sum, part) => sum + part.length, 0);
  const bytes = new Uint8Array(total);
  let at = 0;
  for (const part of parts) {
    bytes.set(part, at);
    at += part.length;
  }
  return bytes;
}

