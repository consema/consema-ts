/**
 * Materializes one `hcl.body@1` record into a new canonical HCL document
 * (RFC 0014 §9). Returns the sealed RFC 0004 §7 union; a failed attempt
 * contains no Document and no partial bytes.
 */
export function materializeHcl(
  record: HclBodyRecordInput,
  request: MaterializationRequest,
): MaterializationResult<HclDocument> {
  const analyzed: ValuePath[] = [];
  try {
    const profile = validateRequest(request);
    const limits = request.limits();
    const body = normalizeBody(record, true);
    tfvarsBlockCheck(profile, body);
    countInputNodes(body, limits);
    const writer = new Writer(limits);
    writeBody(writer, body, 0);
    const bytes = new TextEncoder().encode(writer.finish());
    let document: HclDocument;
    try {
      document = parseHcl(bytes, profile, profileDefaultEncoding(), closureParseLimits(limits));
    } catch {
      throw new MaterializationFailure('FormationFailed');
    }
    if (document.formationStatus() !== 'Complete') {
      throw new MaterializationFailure('FormationFailed');
    }
    const provenance = verifyClosure(body, document, limits);
    const report = new MaterializationReport([], limits);
    const fidelity: MaterializationFidelity = 'Exact';
    return {
      kind: 'Complete',
      value: new CompleteMaterialization(document, fidelity, report, provenance),
    };
  } catch (failure) {
    if (!(failure instanceof MaterializationFailure)) {
      throw failure;
    }
    return {
      kind: 'Failed',
      value: new FailedMaterializationAttempt(failure, new MaterializationReport([], request.limits()), analyzed),
    };
  }
}

/** The exact target profile under the frozen style contract (materialization.rs:266-285). */
function validateRequest(request: MaterializationRequest): HclProfile {
  const target = request.targetProfile();
  const style = request.style();
  let profile: HclProfile;
  if (target.id() === 'hcl.native' && target.version() === 1) {
    profile = HclProfile.NATIVE_V1;
  } else if (target.id() === 'hcl.tfvars' && target.version() === 1) {
    profile = HclProfile.TFVARS_V1;
  } else {
    throw new MaterializationFailure('UnsupportedProfile');
  }
  if (style.id() !== 'hcl.canonical-document' || style.version() !== 1) {
    throw new MaterializationFailure('UnsupportedStyle');
  }
  if (request.encoding().kind !== 'Utf8') {
    throw new MaterializationFailure('UnsupportedEncoding');
  }
  if (request.newline() !== 'Lf') {
    throw new MaterializationFailure('UnsupportedNewline');
  }
  return profile;
}

/** Counts input nodes and container depth before any allocation (RFC 0004 §19). */
function countInputNodes(body: NormalizedBody, limits: MaterializationLimits): void {
  const state = { nodes: 0, depth: 0 };
  const walk = (items: readonly NormalizedItem[], depth: number): void => {
    if (depth > limits.maxDepth) {
      throw new MaterializationFailure('ResourceLimit', { reason: 'input-depth' });
    }
    for (const item of items) {
      state.nodes += 1;
      if (state.nodes > limits.maxInputNodes) {
        throw new MaterializationFailure('ResourceLimit', { reason: 'input-nodes' });
      }
      if (item.kind === 'attribute') {
        walkValue(item.value, depth + 1, state, limits);
      } else {
        walk(item.body.items, depth + 1);
      }
    }
  };
  walk(body.items, 0);
}

function walkValue(
  value: ValueNode,
  depth: number,
  state: { nodes: number; depth: number },
  limits: MaterializationLimits,
): void {
  if (depth > limits.maxDepth) {
    throw new MaterializationFailure('ResourceLimit', { reason: 'input-depth' });
  }
  state.nodes += 1;
  if (state.nodes > limits.maxInputNodes) {
    throw new MaterializationFailure('ResourceLimit', { reason: 'input-nodes' });
  }
  if (value.kind === 'Tuple') {
    for (const element of value.elements) {
      walkValue(element, depth + 1, state, limits);
    }
  } else if (value.kind === 'Object') {
    for (const entry of value.entries) {
      state.nodes += 1;
      if (state.nodes > limits.maxInputNodes) {
        throw new MaterializationFailure('ResourceLimit', { reason: 'input-nodes' });
      }
      walkValue(entry.value, depth + 1, state, limits);
    }
  }
}

// The tfvars profile refuses any record containing a block
// (RFC 0014 §5, §9); the failure carries `hcl.materialization.unrepresentable@1`
// through the conformance code mapping (hcl_v1.rs:1621). The check happens
// in normalizeBody's callers: materializeHcl validates the profile target
// first, then rejects blocks under the tfvars profile here.
function tfvarsBlockCheck(profile: HclProfile, body: NormalizedBody): void {
  if (profile === HclProfile.TFVARS_V1 && body.items.some((item) => item.kind === 'block')) {
    throw new MaterializationFailure('Unrepresentable', { reason: 'tfvars-block' });
  }
}
