class Writer {
  readonly #limits: MaterializationLimits;
  #out = '';

  constructor(limits: MaterializationLimits) {
    this.#limits = limits;
  }

  push(text: string): void {
    const next = this.#out.length + text.length;
    if (next > this.#limits.maxOutputBytes) {
      throw new MaterializationFailure('ResourceLimit', { reason: 'output-bytes' });
    }
    this.#out += text;
  }

  indent(depth: number): void {
    for (let i = 0; i < depth; i++) {
      this.push('  ');
    }
  }

  pushQuoted(text: string): void {
    this.push('"');
    this.push(escapeText(text));
    this.push('"');
  }

  finish(): string {
    return this.#out;
  }
}

/** Escapes one string with the minimal deterministic escape set (materialization.rs:1296-1333). */
export function escapeText(text: string): string {
  let out = '';
  let index = 0;
  while (index < text.length) {
    const byte = text.charCodeAt(index);
    if (byte === 0x24 || byte === 0x25) {
      let run = 1;
      while (index + run < text.length && text.charCodeAt(index + run) === byte) {
        run += 1;
      }
      const doubled = index + run < text.length && text.charCodeAt(index + run) === 0x7b;
      for (let i = 0; i < run + (doubled ? 1 : 0); i++) {
        out += String.fromCharCode(byte);
      }
      index += run;
    } else {
      const character = text[index];
      switch (character) {
        case '"':
          out += '\\"';
          break;
        case '\\':
          out += '\\\\';
          break;
        case '\n':
          out += '\\n';
          break;
        case '\r':
          out += '\\r';
          break;
        case '\t':
          out += '\\t';
          break;
        default: {
          const codePoint = text.codePointAt(index)!;
          if (isEscapedControl(codePoint)) {
            out += `\\u${codePoint.toString(16).padStart(4, '0')}`;
          } else {
            out += character;
          }
          break;
        }
      }
      index += character.length;
    }
  }
  return out;
}

/** C0 controls other than the named escapes, DEL, and the C1 controls (materialization.rs:1280-1286). */
function isEscapedControl(value: number): boolean {
  return value < 0x20 || (value >= 0x7f && value <= 0x9f);
}

/** Whether one text is a valid UAX #31 identifier with the frozen hyphen continuation (materialization.rs:1266-1278). */
function isPlainIdentifier(text: string): boolean {
  if (text.length === 0) {
    return false;
  }
  const first = text.codePointAt(0)!;
  const firstChar = String.fromCodePoint(first);
  if (firstChar === '_' || !/^\p{ID_Start}$/u.test(firstChar)) {
    return false;
  }
  let index = firstChar.length;
  while (index < text.length) {
    const char = text[index];
    if (!/^\p{ID_Continue}$/u.test(char) && char !== '-') {
      return false;
    }
    index += char.length;
  }
  return true;
}

function writeBody(writer: Writer, body: NormalizedBody, depth: number): void {
  for (const item of body.items) {
    if (item.kind === 'attribute') {
      writer.indent(depth);
      writer.push(item.name);
      writer.push(' = ');
      writeValue(writer, item.value, depth);
      writer.push('\n');
    } else {
      writer.indent(depth);
      writer.push(item.type);
      for (const label of item.labels) {
        writer.push(' ');
        writer.pushQuoted(label);
      }
      writer.push(' {\n');
      writeBody(writer, item.body, depth + 1);
      writer.indent(depth);
      writer.push('}\n');
    }
  }
}

function writeValue(writer: Writer, value: ValueNode, depth: number): void {
  switch (value.kind) {
    case 'String':
      writer.pushQuoted(value.text);
      break;
    case 'Integer':
    case 'Real':
      writer.push(value.canonical);
      break;
    case 'Boolean':
      writer.push(value.value ? 'true' : 'false');
      break;
    case 'Null':
      writer.push('null');
      break;
    case 'Tuple': {
      if (value.elements.length === 0) {
        writer.push('[]');
        return;
      }
      writer.push('[\n');
      const last = value.elements.length - 1;
      for (let index = 0; index < value.elements.length; index++) {
        writer.indent(depth + 1);
        writeValue(writer, value.elements[index], depth + 1);
        writer.push(index === last ? '\n' : ',\n');
      }
      writer.indent(depth);
      writer.push(']');
      break;
    }
    case 'Object': {
      if (value.entries.length === 0) {
        writer.push('{}');
        return;
      }
      writer.push('{\n');
      const last = value.entries.length - 1;
      for (let index = 0; index < value.entries.length; index++) {
        writer.indent(depth + 1);
        writeObjectKey(writer, value.entries[index].key);
        writer.push(' = ');
        writeValue(writer, value.entries[index].value, depth + 1);
        writer.push(index === last ? '\n' : ',\n');
      }
      writer.indent(depth);
      writer.push('}');
      break;
    }
    case 'Expression':
      writer.push(value.text);
      break;
  }
}

function writeObjectKey(writer: Writer, key: string): void {
  if (isPlainIdentifier(key) && key !== 'for') {
    writer.push(key);
  } else {
    writer.pushQuoted(key);
  }
}

