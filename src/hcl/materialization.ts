/** Compares the reparsed native model to the promised input semantics (RFC 0014 §9). */
function verifyClosure(
  body: NormalizedBody,
  document: HclDocument,
  limits: MaterializationLimits,
): MaterializationProvenanceMap {
  const entries: MaterializationProvenanceEntry[] = [];
  let units = 0;
  const note = (entry: MaterializationProvenanceEntry): void => {
    units += 1 + entry.outputs().length;
    if (units > limits.maxProvenanceEntries) {
      throw new MaterializationFailure('ResourceLimit', { reason: 'provenance-entries' });
    }
    entries.push(entry);
  };
  verifyBody(body, document.root(), document, ValuePath.root(), note);
  return MaterializationProvenanceMap.create(entries, document.snapshotIdentity(), limits);
}

function verifyBody(
  body: NormalizedBody,
  nativeBody: import('./document.ts').HclBody,
  document: HclDocument,
  path: ValuePath,
  note: (entry: MaterializationProvenanceEntry) => void,
): void {
  const nativeItems = nativeBody.items();
  if (nativeItems.length !== body.items.length) {
    throw new MaterializationFailure('FormationFailed');
  }
  for (let index = 0; index < body.items.length; index++) {
    const promised = body.items[index];
    const native = nativeItems[index];
    const itemPath = path.child({ kind: 'SequenceElement', index: BigInt(index) });
    if (promised.kind === 'attribute') {
      if (!(native instanceof HclAttribute)) {
        throw new MaterializationFailure('FormationFailed');
      }
      if (native.name() !== promised.name) {
        throw new MaterializationFailure('FormationFailed');
      }
      const valuePath = itemPath.child({ kind: 'ObjectValue', name: 'value' });
      verifyValue(promised.value, native.expression(), document, valuePath, note);
    } else {
      if (!(native instanceof HclBlock)) {
        throw new MaterializationFailure('FormationFailed');
      }
      if (native.type() !== promised.type) {
        throw new MaterializationFailure('FormationFailed');
      }
      const nativeLabels = native.labels();
      if (nativeLabels.length !== promised.labels.length) {
        throw new MaterializationFailure('FormationFailed');
      }
      for (let labelIndex = 0; labelIndex < promised.labels.length; labelIndex++) {
        if (nativeLabels[labelIndex].text() !== promised.labels[labelIndex]) {
          throw new MaterializationFailure('FormationFailed');
        }
      }
      const bodyPath = itemPath.child({ kind: 'ObjectValue', name: 'body' });
      note(
        new MaterializationProvenanceEntry(
          { kind: 'Value', path: bodyPath },
          [
            new MaterializedOrigin(
              document.snapshotIdentity(),
              native.nodeRef(),
              native.span(),
              'Direct',
            ),
          ],
        ),
      );
      verifyBody(promised.body, native.body(), document, bodyPath, note);
    }
  }
}

function verifyValue(
  promised: ValueNode,
  native: import('./document.ts').HclExpressionHandle,
  document: HclDocument,
  path: ValuePath,
  note: (entry: MaterializationProvenanceEntry) => void,
): void {
  const node = native.node();
  if (promised.kind === 'Expression') {
    if (kindFamily(expressionKindOf(node)) !== promised.kindName) {
      throw new MaterializationFailure('FormationFailed');
    }
    if (native.text() !== promised.text) {
      throw new MaterializationFailure('FormationFailed');
    }
    if (promised.fingerprint !== null) {
      const actual = expressionFingerprint(node).toString(16).padStart(16, '0');
      if (actual !== promised.fingerprint) {
        throw new MaterializationFailure('FormationFailed');
      }
    }
    note(
      new MaterializationProvenanceEntry(
        { kind: 'Value', path },
        [new MaterializedOrigin(document.snapshotIdentity(), native.nodeRef(), native.span(), 'Direct')],
      ),
    );
    return;
  }
  if (!isLiteralComplete(node)) {
    throw new MaterializationFailure('FormationFailed');
  }
  const literal = literalValue(node);
  if (literal === null) {
    throw new MaterializationFailure('FormationFailed');
  }
  const canonical = literalCanonical(literal);
  switch (promised.kind) {
    case 'String':
      if (literal.kind !== 'String' || literal.text !== promised.text) {
        throw new MaterializationFailure('FormationFailed');
      }
      break;
    case 'Integer':
    case 'Real':
      if (canonical !== promised.canonical) {
        throw new MaterializationFailure('FormationFailed');
      }
      break;
    case 'Boolean':
      if (literal.kind !== 'Boolean' || literal.value !== promised.value) {
        throw new MaterializationFailure('FormationFailed');
      }
      break;
    case 'Null':
      if (literal.kind !== 'Null') {
        throw new MaterializationFailure('FormationFailed');
      }
      break;
    case 'Tuple': {
      if (literal.kind !== 'Tuple' || literal.elements.length !== promised.elements.length) {
        throw new MaterializationFailure('FormationFailed');
      }
      for (let index = 0; index < promised.elements.length; index++) {
        if (literalCanonical(literal.elements[index]) !== valueNodeCanonical(promised.elements[index])) {
          throw new MaterializationFailure('FormationFailed');
        }
      }
      break;
    }
    case 'Object': {
      if (literal.kind !== 'Object' || literal.entries.length !== promised.entries.length) {
        throw new MaterializationFailure('FormationFailed');
      }
      for (let index = 0; index < promised.entries.length; index++) {
        const promisedEntry = promised.entries[index];
        const literalEntry = literal.entries[index];
        const literalKey = literalKeyCanonical(literalEntry.key);
        if (literalKey !== promisedEntry.key) {
          throw new MaterializationFailure('FormationFailed');
        }
        if (literalCanonical(literalEntry.value) !== valueNodeCanonical(promisedEntry.value)) {
          throw new MaterializationFailure('FormationFailed');
        }
      }
      break;
    }
  }
  note(
    new MaterializationProvenanceEntry(
      { kind: 'Value', path },
      [new MaterializedOrigin(document.snapshotIdentity(), native.nodeRef(), native.span(), 'Direct')],
    ),
  );
}

/** The canonical encoding of one promised value node (numbers by canonical-decimal equality). */
function valueNodeCanonical(value: ValueNode): string {
  switch (value.kind) {
    case 'String':
      return `s:${value.text}`;
    case 'Integer':
    case 'Real':
      return value.canonical;
    case 'Boolean':
      return `b:${value.value}`;
    case 'Null':
      return 'null';
    case 'Tuple':
      return `[${value.elements.map(valueNodeCanonical).join(',')}]`;
    case 'Object':
      return `{${value.entries
        .map((entry) => `${entry.key}=${valueNodeCanonical(entry.value)}`)
        .join(',')}}`;
    case 'Expression':
      return `e:${value.text}`;
  }
}

/** The canonical-decimal spelling of one literal value (numbers by canonical-decimal equality). */
function literalCanonical(literal: import('./expression.ts').HclLiteralValue): string {
  switch (literal.kind) {
    case 'Integer':
    case 'Decimal':
      return literal.canonical;
    case 'String':
      return `s:${literal.text}`;
    case 'Boolean':
      return `b:${literal.value}`;
    case 'Null':
      return 'null';
    case 'Tuple':
      return `[${literal.elements.map(literalCanonical).join(',')}]`;
    case 'Object':
      return `{${literal.entries
        .map((entry) => `${literalKeyCanonical(entry.key)}=${literalCanonical(entry.value)}`)
        .join(',')}}`;
  }
}

/** The canonical string spelling of one literal key (RFC 0014 §8.2). */
function literalKeyCanonical(key: import('./expression.ts').HclLiteralKey): string {
  switch (key.kind) {
    case 'Identifier':
      return key.name;
    case 'Number':
      return key.canonical;
    case 'String':
      return key.text;
    case 'Value':
      return literalKeyValueCanonical(key.value);
  }
}

function literalKeyValueCanonical(value: import('./expression.ts').HclLiteralValue): string {
  switch (value.kind) {
    case 'String':
      return value.text;
    case 'Integer':
    case 'Decimal':
      return value.canonical;
    case 'Boolean':
      return value.value ? 'true' : 'false';
    case 'Null':
      return 'null';
    case 'Tuple':
    case 'Object':
      throw new MaterializationFailure('FormationFailed');
  }
}

