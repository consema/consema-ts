type ValueNode =
  | { readonly kind: 'String'; readonly text: string }
  | { readonly kind: 'Integer'; readonly canonical: string }
  | { readonly kind: 'Real'; readonly canonical: string }
  | { readonly kind: 'Boolean'; readonly value: boolean }
  | { readonly kind: 'Null' }
  | { readonly kind: 'Tuple'; readonly elements: readonly ValueNode[] }
  | { readonly kind: 'Object'; readonly entries: readonly { readonly key: string; readonly value: ValueNode }[] }
  | { readonly kind: 'Expression'; readonly kindName: string; readonly text: string; readonly fingerprint: string | null };

interface NormalizedBody {
  readonly items: readonly NormalizedItem[];
}

type NormalizedItem =
  | { readonly kind: 'attribute'; readonly name: string; readonly value: ValueNode }
  | {
      readonly kind: 'block';
      readonly type: string;
      readonly labels: readonly string[];
      readonly body: NormalizedBody;
    };

/** A record is an ordered entry-mapping object only when every element is a `[string, value]` pair. */
function isEntryPair(value: unknown): value is readonly [string, unknown] {
  return (
    Array.isArray(value) &&
    value.length === 2 &&
    typeof value[0] === 'string'
  );
}

function invalidRecord(reason: string): MaterializationFailure {
  return new MaterializationFailure('InvalidRequest', { reason });
}

/**
 * Normalizes one body record; any deviation is InvalidRequest "invalid-record".
 *
 * The `record: "hcl.body@1"` discriminator is required at the top level only
 * (materialization.rs:380-402). A block item's nested body is validated by
 * `Body::validate` (:522-543), which reads only the `items` member, so the
 * published vector spelling `{ "items": [...] }` without the discriminator
 * is accepted at nested levels (hcl-v1.json canonical-document block item).
 */
function normalizeBody(record: unknown, topLevel: boolean): NormalizedBody {
  if (typeof record !== 'object' || record === null || Array.isArray(record)) {
    throw invalidRecord('body-record');
  }
  const body = record as Record<string, unknown>;
  if (topLevel && body.record !== 'hcl.body@1') {
    throw invalidRecord('body-record');
  }
  if (!Array.isArray(body.items)) {
    throw invalidRecord('body-items');
  }
  const items: NormalizedItem[] = [];
  for (const item of body.items) {
    if (typeof item !== 'object' || item === null || Array.isArray(item)) {
      throw invalidRecord('body-item');
    }
    const itemRecord = item as Record<string, unknown>;
    const kind = itemRecord.kind;
    if (kind === 'attribute') {
      if (typeof itemRecord.name !== 'string' || itemRecord.value === undefined) {
        throw invalidRecord('attribute-item');
      }
      items.push({ kind: 'attribute', name: itemRecord.name, value: normalizeValue(itemRecord.value) });
    } else if (kind === 'block') {
      if (
        typeof itemRecord.type !== 'string' ||
        !Array.isArray(itemRecord.labels) ||
        !itemRecord.labels.every((label) => typeof label === 'string') ||
        itemRecord.body === undefined
      ) {
        throw invalidRecord('block-item');
      }
      items.push({
        kind: 'block',
        type: itemRecord.type,
        labels: itemRecord.labels as string[],
        body: normalizeBody(itemRecord.body, false),
      });
    } else {
      throw invalidRecord('body-item');
    }
  }
  return { items };
}

/** Normalizes one attribute value in either spelling (RFC 0014 §9). */
export function normalizeValue(value: unknown): ValueNode {
  if (typeof value === 'string') {
    return { kind: 'String', text: value };
  }
  if (typeof value === 'number') {
    if (Number.isInteger(value)) {
      return { kind: 'Integer', canonical: BigInt(value).toString() };
    }
    return { kind: 'Real', canonical: canonicalRealFromNumber(value) };
  }
  if (typeof value === 'boolean') {
    return { kind: 'Boolean', value };
  }
  if (value === null) {
    return { kind: 'Null' };
  }
  if (Array.isArray(value)) {
    if (value.length > 0 && value.every(isEntryPair)) {
      const entries = value.map(([key, entryValue]) => ({
        key,
        value: normalizeValue(entryValue),
      }));
      return { kind: 'Object', entries };
    }
    const elements = value.map((element) => normalizeValue(element));
    return { kind: 'Tuple', elements };
  }
  if (typeof value === 'object') {
    const record = value as Record<string, unknown>;
    switch (record.kind) {
      case 'string':
        if (typeof record.text !== 'string') {
          throw invalidRecord('string-record');
        }
        return { kind: 'String', text: record.text };
      case 'integer':
        if (typeof record.value !== 'number' && typeof record.value !== 'bigint') {
          throw invalidRecord('integer-record');
        }
        if (typeof record.value === 'number' && !Number.isInteger(record.value)) {
          throw invalidRecord('integer-record');
        }
        return { kind: 'Integer', canonical: BigInt(record.value).toString() };
      case 'real':
        if (typeof record.value !== 'number' || !Number.isFinite(record.value)) {
          throw invalidRecord('real-record');
        }
        return { kind: 'Real', canonical: canonicalRealFromNumber(record.value) };
      case 'boolean':
        if (typeof record.value !== 'boolean') {
          throw invalidRecord('boolean-record');
        }
        return { kind: 'Boolean', value: record.value };
      case 'null':
        return { kind: 'Null' };
      case 'tuple': {
        if (!Array.isArray(record.elements)) {
          throw invalidRecord('tuple-record');
        }
        return { kind: 'Tuple', elements: record.elements.map((element) => normalizeValue(element)) };
      }
      case 'object': {
        if (!Array.isArray(record.entries) || !record.entries.every(isEntryPair)) {
          throw invalidRecord('object-record');
        }
        return {
          kind: 'Object',
          entries: record.entries.map(([key, entryValue]) => ({
            key,
            value: normalizeValue(entryValue),
          })),
        };
      }
      case 'expression': {
        const expression = record.expression as Record<string, unknown> | undefined;
        if (
          typeof expression !== 'object' ||
          expression === null ||
          expression.record !== 'hcl.expression@1' ||
          typeof expression.kind !== 'string' ||
          typeof expression.text !== 'string'
        ) {
          throw invalidRecord('expression-record');
        }
        const fingerprint = expression.fingerprint;
        if (fingerprint !== undefined && typeof fingerprint !== 'string') {
          throw invalidRecord('expression-record');
        }
        return {
          kind: 'Expression',
          kindName: expression.kind,
          text: expression.text,
          fingerprint: typeof fingerprint === 'string' ? fingerprint : null,
        };
      }
      default:
        throw invalidRecord('value-record');
    }
  }
  throw invalidRecord('value-record');
}

/** The canonical decimal spelling of one finite JS number (shortest round-trip). */
export function canonicalRealFromNumber(value: number): string {
  if (value === 0) {
    return '0';
  }
  const text = String(value);
  const exponentIndex = text.search(/[eE]/);
  if (exponentIndex < 0) {
    return text;
  }
  // Fold the exponent into the decimal point position.
  const mantissa = text.slice(0, exponentIndex);
  const exponent = Number(text.slice(exponentIndex + 1));
  const negative = mantissa.startsWith('-');
  const unsigned = negative ? mantissa.slice(1) : mantissa;
  const dot = unsigned.indexOf('.');
  const digits = unsigned.replace('.', '');
  const point = (dot < 0 ? digits.length : dot) + exponent;
  let out: string;
  if (point <= 0) {
    out = `0.${'0'.repeat(-point)}${digits}`;
  } else if (point >= digits.length) {
    out = digits + '0'.repeat(point - digits.length);
  } else {
    out = `${digits.slice(0, point)}.${digits.slice(point)}`;
  }
  if (negative) {
    out = `-${out}`;
  }
  return out;
}

