/**
 * Deterministic canonical HCL materialization: `hcl.canonical-document@1`
 * (RFC 0014 §9).
 *
 * authority:
 *  - RFC 0004 §3 (:57-94) the common MaterializationRequest; §7 (:170-192)
 *    the completion algebra
 *  - RFC 0014 §9 (:574-629): the canonical style — UTF-8 without BOM, LF
 *    line endings, two-space indentation, `name = value` attributes, block
 *    headers as `type "label" {`, a trailing newline after the final item,
 *    minimal deterministic string escapes, canonical decimal spellings,
 *    one-item-per-line tuples and objects with `=` keys, `hcl.expression@1`
 *    records emitting their canonical text, labels always quoted; the two
 *    value spellings (raw typed member or value record with a string
 *    `kind` member); the tfvars profile rejects any record containing a
 *    block; every style validates, encodes, reparses the exact generated
 *    bytes, and compares the reparsed native model to the promised input
 *    semantics — failure returns no target Document, partial bytes, or
 *    partial provenance
 *  - crates/consema-hcl/src/materialization.rs — validate_request :266-285
 *    (only `hcl.native@1`/`hcl.tfvars@1` + the canonical style + UTF-8 +
 *    Lf), the parse limits for the closure reparse :295-328, write_body
 *    :1174-1208, write_value :1211-1253, write_object_key :1255-1264
 *    (bare identifier except `for`), is_plain_identifier :1266-1278,
 *    escape_text :1296-1333 (the `$`/`%` run doubling), render_decimal
 *    :1344-1366, verify_closure :1773-1860 (lockstep comparison by
 *    canonical-decimal equality and structural equality)
 *
 * Design (TypeScript-idiomatic): the input record is a plain JS value
 * tree in either pinned spelling, normalized once into a closed ValueNode
 * tree (any deviation is InvalidRequest "invalid-record"); a bounded byte
 * writer mirrors the Rust writer; the result is the sealed RFC 0004 §7
 * union from the document domain. The reparse closure re-forms the exact
 * generated bytes and walks the input record and the reparsed body in
 * lockstep, comparing numbers by canonical-decimal value equality and
 * everything else structurally (RFC 0014 §6).
 */

